      class="mt-3 overflow-x-auto rounded border border-slate-300 bg-slate-100 px-4 py-3 text-sm text-slate-800 dark:border-slate-700 dark:bg-slate-900 dark:text-slate-100"><code
        >{node.source}</code
      ></pre>
  {/if}
</figure>

