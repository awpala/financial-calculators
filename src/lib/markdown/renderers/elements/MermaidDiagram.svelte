@component
Renders a server-generated Mermaid SVG, falling back to the diagram source when rendering failed.
-->
<script lang="ts">
  import type { MermaidDiagramNode } from '../../types.js';

  /** Public inputs for this component. */
  type Props = {
    /** The diagram, carrying server-rendered SVG or the error that replaced it. */
    node: MermaidDiagramNode;
  };

  let { node }: Props = $props();
</script>

<figure
  class="my-5 overflow-auto rounded-lg border border-slate-300 bg-white p-4 dark:border-slate-700 dark:bg-slate-950"
>
  {#if node.svg}
    <div
      class="mermaid-diagram [&_svg]:mx-auto [&_svg]:h-auto [&_svg]:max-w-full"
    >
      <!-- eslint-disable-next-line svelte/no-at-html-tags -- Only SVG generated by the server with Mermaid strict security is accepted. -->
      {@html node.svg}
    </div>
  {:else}
    <pre
      class="m-0 overflow-x-auto rounded border border-rose-300 bg-rose-50 px-4 py-3 text-sm text-rose-900 dark:border-rose-800 dark:bg-rose-950/30 dark:text-rose-200">{node.error ??
        'Failed to render Mermaid diagram.'}</pre>
